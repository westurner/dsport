//! Minimal native texinfo builder.

use std::path::{Path, PathBuf};

use docutilsrs::{parse_rst_with_source, text};

use super::{BuildError, BuildResult, Builder};
use crate::environment::BuildEnvironment;

#[derive(Debug, Default)]
pub struct TexinfoBuilder;

#[derive(Debug, Clone, PartialEq, Eq)]
struct TexinfoDocument {
    docname: String,
    targetname: String,
    title: String,
    author: String,
    direntry: String,
    description: String,
    category: String,
}

impl TexinfoBuilder {
    pub fn new() -> Self {
        Self
    }

    fn configured_documents(env: &BuildEnvironment) -> Vec<TexinfoDocument> {
        let entries = env
            .config
            .get("texinfo_documents")
            .and_then(|value| value.as_list().map(<[_]>::to_vec))
            .unwrap_or_default();
        if entries.is_empty() && !env.config.raw_config().contains_key("texinfo_documents") {
            let project = env.config.project();
            let targetname = crate::util_osutil::make_filename_from_project(&project);
            return vec![TexinfoDocument {
                docname: env.config.root_doc(),
                targetname: targetname.clone(),
                title: project,
                author: env.config.author(),
                direntry: targetname,
                description: "One line description of project".into(),
                category: "Miscellaneous".into(),
            }];
        }

        entries
            .iter()
            .filter_map(|entry| {
                let fields = entry.as_list()?;
                Some(TexinfoDocument {
                    docname: fields.first()?.as_str()?.to_owned(),
                    targetname: fields.get(1)?.as_str()?.to_owned(),
                    title: fields.get(2)?.as_str()?.to_owned(),
                    author: fields.get(3)?.as_str()?.to_owned(),
                    direntry: fields.get(4)?.as_str()?.to_owned(),
                    description: fields.get(5)?.as_str()?.to_owned(),
                    category: fields.get(6)?.as_str()?.to_owned(),
                })
            })
            .collect()
    }

    fn project_document_order(env: &BuildEnvironment, root: &str) -> Vec<String> {
        fn append(
            entries: &[crate::toctree::TocEntry],
            found: &std::collections::HashSet<String>,
            ordered: &mut Vec<String>,
            seen: &mut std::collections::HashSet<String>,
        ) {
            for entry in entries {
                if (found.is_empty() || found.contains(&entry.docname))
                    && seen.insert(entry.docname.clone())
                {
                    ordered.push(entry.docname.clone());
                }
                append(&entry.children, found, ordered, seen);
            }
        }

        let mut ordered = vec![root.to_owned()];
        let mut seen = std::collections::HashSet::from([root.to_owned()]);
        append(
            &crate::toctree::resolve(env, root, 0),
            env.found_docs(),
            &mut ordered,
            &mut seen,
        );
        ordered
    }

    fn document_body(
        srcdir: &Path,
        env: &BuildEnvironment,
        docname: &str,
    ) -> Result<String, BuildError> {
        let tree = match env.get_and_resolve_doctree(docname) {
            Ok(tree) => tree,
            Err(_) => {
                let path =
                    super::html::src_path_for_docname_with_suffixes(srcdir, docname, &env.config)?;
                let source =
                    crate::environment::read_source_file(&path, &env.config.source_encoding())
                        .map_err(|error| {
                            BuildError::Other(format!("failed to read {}: {error}", path.display()))
                        })?;
                parse_rst_with_source(&source, docname)
            }
        };
        Ok(text(&tree))
    }

    fn write_project_document(
        srcdir: &Path,
        outdir: &Path,
        env: &BuildEnvironment,
        document: &TexinfoDocument,
    ) -> Result<(), BuildError> {
        let mut body = String::new();
        for docname in Self::project_document_order(env, &document.docname) {
            body.push_str(&Self::document_body(srcdir, env, &docname)?);
            body.push_str("\n\n");
        }
        let targetname = texinfo_escape(&document.targetname);
        let title = texinfo_escape(&document.title);
        let author = texinfo_escape(&document.author);
        let category = texinfo_escape(&document.category);
        let direntry = texinfo_escape(&document.direntry);
        let description = texinfo_escape(&document.description);
        let body = texinfo_escape(&body);
        let output = format!(
            "\\input texinfo   @c -*-texinfo-*-\n@c %%**start of header\n@setfilename {targetname}.info\n@documentencoding UTF-8\n@ifinfo\n@*Generated by sphinxdocrs.@*\n@end ifinfo\n@settitle {title}\n@defindex ge\n@paragraphindent 0\n@exampleindent 4\n@finalout\n@dircategory {category}\n@direntry\n* {direntry}: ({targetname}). {description}\n@end direntry\n@c %%**end of header\n\n@copying\n{title}\n\n{author}\n@end copying\n\n@titlepage\n@title {title}\n@insertcopying\n@end titlepage\n@contents\n\n@c %%**start of body\n@node Top\n@top {title}\n@insertcopying\n\n{body}@c %%**end of body\n@bye\n"
        );
        let path = outdir.join(format!("{}.texi", document.targetname));
        ensure_output_parent(&path, outdir)?;
        std::fs::write(path, output)?;
        Ok(())
    }
}

impl Builder for TexinfoBuilder {
    fn name(&self) -> &str {
        "texinfo"
    }
    fn format(&self) -> &str {
        "texinfo"
    }
    fn out_suffix(&self) -> &str {
        ".texi"
    }
    fn get_target_uri(&self, docname: &str) -> String {
        format!("{docname}.texi")
    }

    fn build_doc(&self, docname: &str, source: &str, outdir: &Path) -> Result<(), BuildError> {
        let tree = parse_rst_with_source(source, docname);
        let body = text(&tree);
        let title = docname.rsplit('/').next().unwrap_or(docname);
        let output = format!(
            "\\input texinfo\n@setfilename {title}.info\n@settitle {title}\n\n{body}\n@bye\n"
        );
        let rel: PathBuf = docname
            .split('/')
            .collect::<PathBuf>()
            .with_extension("texi");
        let path = outdir.join(rel);
        ensure_output_parent(&path, outdir)?;
        std::fs::write(path, output)?;
        Ok(())
    }

    fn build_all(
        &self,
        srcdir: &Path,
        outdir: &Path,
        env: &BuildEnvironment,
    ) -> Result<BuildResult, BuildError> {
        std::fs::create_dir_all(outdir)?;
        std::fs::write(
            outdir.join("Makefile"),
            include_bytes!("../../../sphinx/sphinx/templates/texinfo/Makefile"),
        )?;
        let configured = Self::configured_documents(env);
        for document in &configured {
            Self::write_project_document(srcdir, outdir, env, document)?;
        }
        Ok(BuildResult {
            written: configured.len(),
            ..BuildResult::default()
        })
    }
}

fn texinfo_escape(value: &str) -> String {
    value
        .replace('@', "@@")
        .replace('{', "@{")
        .replace('}', "@}")
}

fn ensure_output_parent(path: &Path, fallback: &Path) -> Result<(), BuildError> {
    std::fs::create_dir_all(path.parent().unwrap_or(fallback))?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    use tempfile::TempDir;

    fn test_environment(srcdir: &Path, doctreedir: &Path) -> BuildEnvironment {
        let project = crate::environment::EnvProject::new(srcdir, &[(".rst", "restructuredtext")]);
        BuildEnvironment::new(
            crate::config::SphinxConfig::new_defaults(),
            project,
            srcdir,
            doctreedir,
        )
    }

    #[test]
    fn configured_documents_skips_invalid_tuple_shapes_and_fields() {
        use crate::config::ConfigVal;

        let src = TempDir::new().unwrap();
        let doctrees = TempDir::new().unwrap();
        let mut env = test_environment(src.path(), doctrees.path());
        let text = |value: &str| ConfigVal::Str(value.to_owned());
        let mut entries = vec![text("not a tuple"), ConfigVal::List(Vec::new())];
        for field_count in 0..7 {
            entries.push(ConfigVal::List(
                (0..field_count)
                    .map(|index| text(&format!("field{index}")))
                    .collect(),
            ));
        }
        for invalid_index in 0..7 {
            let mut fields: Vec<_> = (0..7).map(|index| text(&format!("field{index}"))).collect();
            fields[invalid_index] = ConfigVal::Int(1);
            entries.push(ConfigVal::List(fields));
        }
        entries.push(ConfigVal::List(vec![
            text("index"),
            text("custom"),
            text("Custom title"),
            text("Ada Lovelace"),
            text("Custom entry"),
            text("Description"),
            text("Category"),
        ]));
        env.config
            .set("texinfo_documents", ConfigVal::List(entries));

        assert_eq!(
            TexinfoBuilder::configured_documents(&env),
            vec![TexinfoDocument {
                docname: "index".into(),
                targetname: "custom".into(),
                title: "Custom title".into(),
                author: "Ada Lovelace".into(),
                direntry: "Custom entry".into(),
                description: "Description".into(),
                category: "Category".into(),
            }]
        );
    }

    #[test]
    fn project_document_order_handles_empty_inventory_missing_docs_and_duplicates() {
        let src = TempDir::new().unwrap();
        let doctrees = TempDir::new().unwrap();
        let mut env = test_environment(src.path(), doctrees.path());
        env.toctree_includes
            .insert("index".into(), vec!["guide".into(), "guide".into()]);
        assert_eq!(
            TexinfoBuilder::project_document_order(&env, "index"),
            vec!["index", "guide"]
        );

        env.project.docnames.insert("guide".into());
        env.toctree_includes.insert(
            "index".into(),
            vec!["guide".into(), "missing".into(), "guide".into()],
        );
        assert_eq!(
            TexinfoBuilder::project_document_order(&env, "index"),
            vec!["index", "guide"]
        );
    }

    #[test]
    fn document_body_reports_source_read_failures() {
        let src = TempDir::new().unwrap();
        let doctrees = TempDir::new().unwrap();
        std::fs::write(src.path().join("broken.rst"), [0xff]).unwrap();
        let env = test_environment(src.path(), doctrees.path());

        let error = TexinfoBuilder::document_body(src.path(), &env, "broken").unwrap_err();
        assert!(error.to_string().contains("failed to read"));
    }

    #[test]
    fn output_parent_creation_handles_parented_and_parentless_paths() {
        let out = TempDir::new().unwrap();
        let nested = out.path().join("nested").join("output.texi");
        ensure_output_parent(&nested, out.path()).unwrap();
        assert!(nested.parent().unwrap().is_dir());

        assert!(Path::new("").parent().is_none());
        ensure_output_parent(Path::new(""), out.path()).unwrap();
    }

    #[test]
    fn build_all_propagates_makefile_write_failure() {
        let src = TempDir::new().unwrap();
        let out = TempDir::new().unwrap();
        let doctrees = TempDir::new().unwrap();
        std::fs::create_dir(out.path().join("Makefile")).unwrap();
        let env = test_environment(src.path(), doctrees.path());

        assert!(
            TexinfoBuilder::new()
                .build_all(src.path(), out.path(), &env)
                .is_err()
        );
    }

    #[test]
    fn project_document_write_failure_is_returned() {
        let src = TempDir::new().unwrap();
        let out = TempDir::new().unwrap();
        let doctrees = TempDir::new().unwrap();
        std::fs::write(src.path().join("index.rst"), "Title\n=====\n\nBody.\n").unwrap();
        std::fs::create_dir(out.path().join("custom.texi")).unwrap();
        let env = test_environment(src.path(), doctrees.path());
        let document = TexinfoDocument {
            docname: "index".into(),
            targetname: "custom".into(),
            title: "Title".into(),
            author: "Author".into(),
            direntry: "Entry".into(),
            description: "Description".into(),
            category: "Category".into(),
        };

        assert!(
            TexinfoBuilder::write_project_document(src.path(), out.path(), &env, &document)
                .is_err()
        );
    }

    #[test]
    fn writes_texinfo_header_and_body() {
        let out = TempDir::new().unwrap();
        TexinfoBuilder::new()
            .build_doc("index", "Title\n=====\n\nBody.\n", out.path())
            .unwrap();
        let output = std::fs::read_to_string(out.path().join("index.texi")).unwrap();
        assert!(output.starts_with("\\input texinfo\n"));
        assert!(output.contains("Body."));
        assert!(output.ends_with("@bye\n"));
    }

    #[test]
    fn texinfo_escapes_control_characters() {
        assert_eq!(texinfo_escape("@{}"), "@@@{@}");
    }

    #[test]
    fn trait_metadata_and_nested_build_doc_path() {
        let out = TempDir::new().unwrap();
        let builder = TexinfoBuilder::new();
        assert_eq!(builder.name(), "texinfo");
        assert_eq!(builder.format(), "texinfo");
        assert_eq!(builder.out_suffix(), ".texi");
        assert_eq!(builder.get_target_uri("guide/intro"), "guide/intro.texi");
        builder
            .build_doc("guide/intro", "Intro\n=====\n\nBody.\n", out.path())
            .unwrap();
        assert!(out.path().join("guide/intro.texi").is_file());
    }

    #[test]
    fn build_all_uses_project_target_and_reports_missing_configured_sources() {
        let src = TempDir::new().unwrap();
        let out = TempDir::new().unwrap();
        std::fs::create_dir_all(src.path().join("guide")).unwrap();
        std::fs::write(src.path().join("index.rst"), "Index\n=====\n").unwrap();
        std::fs::write(src.path().join("guide/intro.rst"), "Intro\n=====\n").unwrap();
        let project =
            crate::environment::EnvProject::new(src.path(), &[(".rst", "restructuredtext")]);
        let mut env = BuildEnvironment::new(
            crate::config::SphinxConfig::new_defaults(),
            project,
            src.path(),
            out.path(),
        );
        env.config.set(
            "project",
            crate::config::ConfigVal::Str("Texinfo Test".into()),
        );
        let builder = TexinfoBuilder::new();
        assert_eq!(
            builder
                .build_all(src.path(), out.path(), &env)
                .unwrap()
                .written,
            1
        );
        assert!(out.path().join("texinfotest.texi").is_file());

        env.config.set(
            "texinfo_documents",
            crate::config::ConfigVal::List(vec![crate::config::ConfigVal::List(vec![
                crate::config::ConfigVal::Str("missing".into()),
                crate::config::ConfigVal::Str("missing-target".into()),
                crate::config::ConfigVal::Str("Missing".into()),
                crate::config::ConfigVal::Str("Author".into()),
                crate::config::ConfigVal::Str("Missing".into()),
                crate::config::ConfigVal::Str("Missing source".into()),
                crate::config::ConfigVal::Str("Miscellaneous".into()),
            ])]),
        );
        let error_out = TempDir::new().unwrap();
        assert!(
            builder
                .build_all(src.path(), error_out.path(), &env)
                .is_err()
        );
    }
}
