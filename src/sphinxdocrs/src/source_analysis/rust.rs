    #[test]
    fn cache_identity_includes_rustdoc_schema_and_hashed_toolchain() {
        let request = SourceAnalysisRequest::new("fixture");
        let toolchain = RustdocJsonAnalyzer::new(Some("rustc-private-path".into()));
        let changed_toolchain = RustdocJsonAnalyzer::new(Some("rustc-other".into()));
        let unspecified_toolchain = RustdocJsonAnalyzer::default();
        let identity = toolchain.cache_identity(&request);

        assert!(identity.contains(BACKEND_VERSION));
        assert!(identity.contains(&format!("format-{}", rustdoc::FORMAT_VERSION)));
        assert!(!identity.contains("rustc-private-path"));
        assert_ne!(identity, changed_toolchain.cache_identity(&request));
        assert_ne!(identity, unspecified_toolchain.cache_identity(&request));
    }

    #[test]
    fn positions_convert_one_based_rustdoc_columns() {
        let value = b"one\ntwo\n";
        let position = position((2, 2), value);
        assert_eq!(position.byte, 5);
        assert_eq!(position.line, 2);
        assert_eq!(position.column, 1);
    }

    #[test]
    fn type_renderer_preserves_common_rust_forms() {
        let value = rustdoc::Type::BorrowedRef {
            lifetime: Some("'a".to_string()),
            is_mutable: true,
            type_: Box::new(rustdoc::Type::Primitive("str".to_string())),
        };
        assert_eq!(render_type(&value), "&'a mut str");

        let tuple = rustdoc::Type::Tuple(vec![
            rustdoc::Type::Primitive("u8".to_string()),
            rustdoc::Type::Infer,
        ]);
        assert_eq!(render_type(&tuple), "(u8, _)");
    }

    #[test]
    fn fixture_json_lowers_api_metadata_and_reexports_deterministically() {
        let fixture_root = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/h14/rust");
        let json_path = fixture_root.parent().unwrap().join("rustdoc.json");
        let bytes = fs::read(&json_path).unwrap();
        let request = SourceAnalysisRequest::new(&fixture_root);
        let analyzer = RustdocJsonAnalyzer::new(Some("fixture-toolchain".to_string()));
        let first = analyzer.analyze_json_bytes(&request, &json_path, &bytes).unwrap();
        let second = analyzer.analyze_json_bytes(&request, &json_path, &bytes).unwrap();
        assert_eq!(first.declarations, second.declarations);
        assert_eq!(first.toolchain.as_deref(), Some("fixture-toolchain"));

        let component = first
            .declarations
            .iter()
            .find(|declaration| declaration.qualified_name == "fixture::api::Component")
            .unwrap();
        assert_eq!(component.aliases, vec!["fixture::PublicComponent"]);
        assert!(!component.children.is_empty());
        assert!(first
            .declarations
            .iter()
            .any(|declaration| declaration.qualified_name == "fixture::api::Component::value"));

        let answer = first
            .declarations
            .iter()
            .find(|declaration| declaration.qualified_name == "fixture::api::answer")
            .unwrap();
        assert_eq!(answer.signature.as_deref(), Some("fn<T>(value: T) -> T"));
        assert_eq!(answer.documentation, "Return the answer.");
        assert_eq!(answer.attributes.get("doc-link:Component").map(String::as_str), Some("2"));
        assert_eq!(answer.source.path, "src/api.rs");
        assert_eq!(answer.source.start.line, 9);

        let hidden = first
            .declarations
            .iter()
            .find(|declaration| declaration.qualified_name == "fixture::hidden_item")
            .unwrap();
        assert!(hidden.noindex);
        assert!(first
            .declarations
            .iter()
            .all(|declaration| declaration.qualified_name != "fixture::private_item"));

        let mut include_private = request.clone();
        include_private.include_private = true;
        let private_snapshot = analyzer
            .analyze_json_bytes(&include_private, &json_path, &bytes)
            .unwrap();
        assert!(private_snapshot
            .declarations
            .iter()
            .any(|declaration| declaration.qualified_name == "fixture::private_item"));
        assert!(first
            .declarations
            .iter()
            .find(|declaration| declaration.qualified_name == "fixture::old_answer")
            .is_some_and(|declaration| declaration.deprecated));
    }

    #[test]
    fn rejects_fixture_with_an_unsupported_format_version() {
        let fixture_root = Path::new(env!("CARGO_MANIFEST_DIR")).join("tests/fixtures/h14/rust");
        let json_path = fixture_root.parent().unwrap().join("rustdoc.json");
        let bytes = fs::read_to_string(&json_path)
            .unwrap()
            .replace("\"format_version\": 61", "\"format_version\": 60");
        let error = RustdocJsonAnalyzer::default()
            .analyze_json_bytes(
                &SourceAnalysisRequest::new(&fixture_root),
                &json_path,
                bytes.as_bytes(),
            )
            .unwrap_err();
        assert!(matches!(error, AnalysisError::BackendUnavailable { .. }));
        assert!(error.to_string().contains("expects 61"));
    }
